/** An SVG path's drawing commands: command letters, numbers, signs, dots, commas and spaces only. */
const PATH_DATA = /^[MmLlHhVvCcSsQqTtAaZz0-9eE.,\-+\s]+$/;
const ID = /^[tc]-[a-z0-9-]+$/;

async function mark(slug) {
  const res = await fetch(`https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}/icons/${slug}.svg`, {
    headers: { accept: 'image/svg+xml', 'user-agent': 'hoomuch-icons-update' },
  });
  if (!res.ok) return null;
  const svg = await res.text();
  const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]*)"/g)].map((m) => m[1]);
  if (!/viewBox="0 0 24 24"/.test(svg) || paths.length === 0 || paths.some((d) => !PATH_DATA.test(d))) return null;
  return paths;
}

const symbols = [];
const missing = [];
for (const [id, slug] of Object.entries(MARKS)) {
  if (!ID.test(id)) throw new Error(`Bad symbol id: ${id}`);
  const paths = await mark(slug);
  if (!paths) {
    missing.push(`${id} (${slug})`);
    continue;
  }
  symbols.push([id, paths]);
}

const sprite =
  `<svg xmlns="http://www.w3.org/2000/svg">\n` +
  `<!-- Generated by scripts/update-tech-icons.mjs from Simple Icons ${VERSION} (https://simpleicons.org, CC0-1.0).\n` +
  `     The marks belong to their owners and are shown only to say a product uses them. Don't edit by hand. -->\n` +
  symbols.map(([id, paths]) => `<symbol id="${id}" viewBox="0 0 24 24">${paths.map((d) => `<path d="${d}"/>`).join('')}</symbol>\n`).join('') +
  `</svg>\n`;
await writeFile(SPRITE, sprite);

const ids =
  `/**\n * The brand marks in public/brand-icons.svg. Generated by scripts/update-tech-icons.mjs\n` +
  ` * (npm run icons:update) from Simple Icons ${VERSION}; don't edit by hand. Owner: Experience (design).\n */\n\n` +
  `export const BRAND_ICON_IDS: ReadonlySet<string> = new Set([\n${symbols.map(([id]) => `  '${id}',\n`).join('')}]);\n`;
await writeFile(IDS, ids);

console.log(`Wrote ${symbols.length} marks to public/brand-icons.svg.`);
if (missing.length > 0) console.log(`Not in Simple Icons ${VERSION}, left out: ${missing.join(', ')}`);
