#!/usr/bin/env node
/**
 * Builds public/brand-icons.svg, the brand marks a product's About section shows beside its tech
 * stack and marketing channels (SPEC F-21), from Simple Icons (https://simpleicons.org, CC0-1.0).
 *
 *   npm run icons:update
 *
 * Pinned to one Simple Icons release, so a refresh is a normal reviewed diff, never a fetch at
 * runtime. Each mark becomes a <symbol> the page draws with <use href="/brand-icons.svg#…">, in
 * the text's colour. Only a path's drawing commands are copied (checked against a strict
 * pattern), so nothing else in an upstream file can reach the sprite. A slug that isn't in the
 * release is reported and left out: its chip shows a plain icon instead.
 *
 * Also writes src/views/components/brand-icon-ids.ts, the symbols the sprite has, so a page never
 * points at one that isn't there.
 */

