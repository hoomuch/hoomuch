#!/usr/bin/env node
/**
 * Refreshes src/lib/disposable-domains.ts from the community blocklist at
 * https://github.com/disposable-email-domains/disposable-email-domains (CC0-1.0).
 *
 *   npm run domains:update
 *
 * The list is pinned to the upstream commit it came from, so a refresh is a normal reviewed diff,
 * never a fetch at runtime. Every line is checked against a strict domain pattern before it is
 * written: the file is data, and nothing in it can break out of the template literal it lands in.
 */

import { writeFile } from 'node:fs/promises';

const REPO = 'disposable-email-domains/disposable-email-domains';
const FILE = 'disposable_email_blocklist.conf';
const OUT = new URL('../src/lib/disposable-domains.ts', import.meta.url);
/** Lowercase labels of letters, digits and hyphens (punycode included), at least two of them. */
const DOMAIN = /^(?=.{4,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,61}[a-z0-9]$/;

async function get(url, accept) {
  const res = await fetch(url, { headers: { accept, 'user-agent': 'hoomuch-domain-update' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res;
}

const commit = await (await get(`https://api.github.com/repos/${REPO}/commits/main`, 'application/vnd.github+json')).json();
const sha = String(commit.sha ?? '');
if (!/^[0-9a-f]{40}$/.test(sha)) throw new Error('Unexpected commit response from GitHub.');
const date = String(commit.commit?.committer?.date ?? '').slice(0, 10);

const text = await (await get(`https://raw.githubusercontent.com/${REPO}/${sha}/${FILE}`, 'text/plain')).text();
const domains = new Set();
const rejected = [];
for (const raw of text.split('\n')) {
  const line = raw.trim().toLowerCase();
  if (!line || line.startsWith('#')) continue;
  if (DOMAIN.test(line)) domains.add(line);
  else rejected.push(line);
}
if (domains.size < 1000) throw new Error(`Only ${domains.size} domains parsed; refusing to write a suspiciously short list.`);

const sorted = [...domains].sort();
const body = `/**
 * Disposable email domains, refused at sign-up (lib/disposable-email.ts).
 * GENERATED by scripts/update-disposable-domains.mjs. Don't edit by hand: run \`npm run domains:update\`.
 *
 * Source: https://github.com/${REPO}
 * Commit: ${sha}${date ? ` (${date})` : ''}
 * License: CC0-1.0 (public domain dedication). ${sorted.length} domains.
 */

export const DISPOSABLE_DOMAINS_COMMIT = '${sha}';

export const DISPOSABLE_DOMAINS = \`
${sorted.join('\n')}
\`;
`;
await writeFile(OUT, body);
console.log(`Wrote ${sorted.length} domains from ${REPO}@${sha.slice(0, 7)}${date ? ` (${date})` : ''}.`);
if (rejected.length) console.log(`Skipped ${rejected.length} malformed line(s): ${rejected.slice(0, 5).join(', ')}${rejected.length > 5 ? ', …' : ''}`);
